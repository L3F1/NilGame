// FLAT 3-MANIFOLDS: E^3 quotiented by a lattice.
//
// The fifth geometry, and the first one here that is deliberately BORING to
// look at. Everything else in this project exists because it does something a
// flat world cannot; this one exists to be the thing they are measured
// against, and it earns its place three times over:
//
// 1. IT IS THE ONLY WORLD WHERE A PORTED MAP IS THE MAP. `port.js` spends
//    seven hundred lines on the fact that there is no isometric embedding
//    between surfaces of different curvature, and every strategy in it trades
//    one exact property for two wrong ones. Port a flat floor plan into E^3
//    and there is nothing to trade: every length, every angle, every straight
//    wall, exactly. So the same plan can be built here and in H^3 and PLAYED
//    BACK TO BACK, which turns "what does curvature do to a level" from an
//    argument into a comparison. `E3T_PLAN` below is that plan, and
//    `tools/port-map.js` will carry it into either hyperbolic world.
//
// 2. IT IS THE EXACT STRUCTURAL MIRROR OF THE TWO HYPERBOLIC WORLDS. The
//    option is the same option:
//
//        floor (2D wrap)   H^3:  octagon -> genus-2 surface x R
//                          E^3:  square  -> 2-torus x R
//        open  (3D wrap)   H^3:  Seifert-Weber dodecahedral space
//                          E^3:  the 3-torus
//
//    and the square cell's inradius is 1.50 against the octagon's 1.5286, so
//    the two are very nearly the same size of room. Same level, same course,
//    same controls, one switch, and the only difference is the curvature.
//
// 3. THE 3-TORUS DOES A THING NO OTHER WORLD HERE CAN. See "gravity without a
//    height" below. It is the cleanest demonstration in the project of what
//    "the field must descend to the quotient" actually means.
//
// The geometry itself is `geom.js` at k = 0 and nothing else -- that is what
// geom.js is FOR, and this file is the payoff for having written it. What is
// local to here is the lattice, the level, and the walking.
//
// No DOM and no graphics, so it is testable.

